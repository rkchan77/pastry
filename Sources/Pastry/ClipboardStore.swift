import AppKit

/// One entry in the history: every representation of every pasteboard item,
/// so text, rich text, images and files all paste back exactly as copied.
struct ClipItem: Identifiable {
    let id = UUID()
    let payload: [[NSPasteboard.PasteboardType: Data]]
    let title: String?      // text preview or file name
    let image: NSImage?     // thumbnail for copied images
    let signature: Int      // used to de-duplicate
}

/// Stack of the last `capacity` clipboard entries, newest first.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    let capacity = 10

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Markers password managers and other apps set to ask not to be recorded.
    private let ignoredMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private let maxBytesPerType = 20 * 1024 * 1024

    func start() {
        let t = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else { return }

        let allTypes = pbItems.flatMap { $0.types.map(\.rawValue) }
        if allTypes.contains(where: ignoredMarkers.contains) { return }

        var payload: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pbItems {
            var reps: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let d = item.data(forType: type), d.count <= maxBytesPerType { reps[type] = d }
            }
            if !reps.isEmpty { payload.append(reps) }
        }
        guard !payload.isEmpty else { return }

        let first = pbItems[0]
        var title: String?
        var image: NSImage?
        if let urlString = first.string(forType: .fileURL), let url = URL(string: urlString) {
            title = pbItems.count > 1 ? "\(url.lastPathComponent) + \(pbItems.count - 1) more" : url.lastPathComponent
        } else if let text = first.string(forType: .string) {
            title = text
        } else if first.types.contains(.png) || first.types.contains(.tiff) {
            image = NSImage(pasteboard: pb)
        }
        guard title != nil || image != nil else { return }

        let signature = title?.hashValue ?? payload[0].values.first?.hashValue ?? 0
        push(ClipItem(payload: payload, title: title, image: image, signature: signature))
    }

    private func push(_ item: ClipItem) {
        items.removeAll { $0.signature == item.signature }   // move duplicates to top
        items.insert(item, at: 0)
        if items.count > capacity { items.removeLast(items.count - capacity) } // evict oldest
    }

    // MARK: Actions

    /// Puts an entry back on the system clipboard and moves it to the top.
    func restore(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let objects: [NSPasteboardItem] = item.payload.map { reps in
            let pi = NSPasteboardItem()
            for (type, data) in reps { pi.setData(data, forType: type) }
            return pi
        }
        pb.writeObjects(objects)
        lastChange = pb.changeCount          // don't re-capture our own write
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}
